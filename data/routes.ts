/**
 * Get route by URL slug (e.g. 'shipping-from-china-to-usa')
 */
export function getRouteBySlug(slug: string): CountryRoute | undefined {
  const normalized = slug.toLowerCase().trim();
  return TARGET_ROUTES.find((r) => r.slug.toLowerCase() === normalized);
}

/**
 * Get all available route slugs for Next.js generateStaticParams
 */
export function getAllRouteSlugs(): string[] {
  return TARGET_ROUTES.map((r) => r.slug);
}

/**
 * Get route by 2-letter ISO country code (e.g. 'US', 'DE', 'GB')
 */
export function getRouteByCode(code: string): CountryRoute | undefined {
  const normalized = code.toUpperCase().trim();
  return TARGET_ROUTES.find((r) => r.code.toUpperCase() === normalized);
}

/**
 * Get routes grouped or filtered by geographical region
 */
export function getRoutesByRegion(region: string): CountryRoute[] {
  const normalized = region.toLowerCase().trim();
  return TARGET_ROUTES.filter((r) => r.region.toLowerCase() === normalized);
}

/**
 * Get summary list of all target routes for dropdowns and navigation menus
 */
export function getRouteSummaryList(): Array<{ code: string; name: string; slug: string; flag: string; region: string }> {
  return TARGET_ROUTES.map((r) => ({
    code: r.code,
    name: r.name,
    slug: r.slug,
    flag: r.flag,
    region: r.region,
  }));
}
